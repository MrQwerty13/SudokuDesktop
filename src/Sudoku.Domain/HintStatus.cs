namespace Sudoku.Domain;

/// <summary>
/// Итог запроса подсказки.
/// </summary>
public enum HintStatus
{
    /// <summary>
    /// Подсказка заполнила пустую ячейку правильным значением.
    /// </summary>
    Revealed = 0,

    /// <summary>
    /// Подсказка исправила значение, введённое игроком: ячейка получила правильное значение.
    /// </summary>
    Corrected = 1,

    /// <summary>
    /// Ячейка исходная (заданная): подсказка не применялась, но правильное значение
    /// возвращено для показа.
    /// </summary>
    AlreadyGiven = 2,

    /// <summary>
    /// Пустых клеток не осталось, подсказывать нечего.
    /// </summary>
    NoEmptyCells = 3,

    /// <summary>
    /// Игра уже завершена, подсказки не нужны.
    /// </summary>
    GameCompleted = 4,
}
